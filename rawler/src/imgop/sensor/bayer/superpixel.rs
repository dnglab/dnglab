use crate::{
  CFA,
  cfa::PlaneColor,
  imgop::{
    Dim2, Point, Rect,
    sensor::{Demosaic, bayer::RgbBayerPattern, check_2x2, check_bayer_rgb, check_mosaic},
  },
  pixarray::{Color2D, ImageRegion},
};
use rayon::prelude::*;

/// Region with an even width and height: the size must be aligned on the
/// Bayer pattern, so deleting the rightmost bit will do the job.
fn even_region(pixels: ImageRegion<'_, f32>) -> ImageRegion<'_, f32> {
  pixels.region(Rect::new(Point::zero(), Dim2::new(pixels.width() & !1, pixels.height() & !1)))
}

#[derive(Default)]
pub struct Superpixel3Channel {}

impl Superpixel3Channel {
  pub fn new() -> Self {
    Self {}
  }
}

impl Demosaic<f32, 3> for Superpixel3Channel {
  /// Debayer image by using superpixel method.
  /// Each output pixel RGB tuple is generated by 4 pixels from input.
  /// The result image is 1/4 of size.
  fn demosaic(&self, pixels: ImageRegion<'_, f32>, cfa: &CFA, colors: &PlaneColor) -> crate::Result<Color2D<f32, 3>> {
    check_mosaic::<3, f32>("Superpixel", &pixels, cfa, colors)?;
    check_bayer_rgb("Superpixel", cfa)?;
    let pixels = even_region(pixels);
    let roi = pixels.area();
    // A region without pixels has no rows
    if roi.is_empty() {
      return Ok(Color2D::new(roi.d.w >> 1, roi.d.h >> 1));
    }
    log::debug!("Superpixel debayer ROI: {:?}", roi);

    let cfa = cfa.shift(roi.p.x, roi.p.y);
    let pattern = match cfa.name.as_str() {
      "RGGB" => RgbBayerPattern::RGGB,
      "BGGR" => RgbBayerPattern::BGGR,
      "GBRG" => RgbBayerPattern::GBRG,
      "GRBG" => RgbBayerPattern::GRBG,
      name => return Err(input_error!("Superpixel needs a Bayer RGB CFA pattern, not '{}'", name)),
    };

    let out = (0..roi.height() / 2)
      .into_par_iter()
      .map(|i| {
        let (r1, r2) = (pixels.row(2 * i), pixels.row(2 * i + 1));
        r1.chunks_exact(2)
          .zip(r2.chunks_exact(2))
          .map(|(a, b)| {
            let p = [a[0], a[1], b[0], b[1]];
            match pattern {
              RgbBayerPattern::RGGB => [p[0], (p[1] + p[2]) / 2.0, p[3]],
              RgbBayerPattern::BGGR => [p[3], (p[1] + p[2]) / 2.0, p[0]],
              RgbBayerPattern::GBRG => [p[2], (p[0] + p[3]) / 2.0, p[1]],
              RgbBayerPattern::GRBG => [p[1], (p[0] + p[3]) / 2.0, p[2]],
            }
          })
          .collect::<Vec<_>>()
      })
      .flatten()
      .collect();
    Ok(Color2D::new_with(out, roi.d.w >> 1, roi.d.h >> 1))
  }
}

#[derive(Default)]
pub struct Superpixel4Channel {}

impl Superpixel4Channel {
  pub fn new() -> Self {
    Self {}
  }
}

impl Demosaic<f32, 4> for Superpixel4Channel {
  /// Debayer image by using superpixel method.
  /// Each output pixel RGB tuple is generated by 4 pixels from input.
  /// The result image is 1/4 of size.
  fn demosaic(&self, pixels: ImageRegion<'_, f32>, cfa: &CFA, colors: &PlaneColor) -> crate::Result<Color2D<f32, 4>> {
    check_mosaic::<4, f32>("Superpixel", &pixels, cfa, colors)?;
    check_2x2("Superpixel", cfa)?;
    let pixels = even_region(pixels);
    let roi = pixels.area();
    // A region without pixels has no rows
    if roi.is_empty() {
      return Ok(Color2D::new(roi.d.w >> 1, roi.d.h >> 1));
    }
    log::debug!("Superpixel debayer ROI: {:?}", roi);

    let cfa = cfa.shift(roi.p.x, roi.p.y);
    // Index into colormap is plane number, value is the index into 2x2 Bayer superpixel.
    let mut colormap = [0; 4];
    for (index, color) in colormap.iter_mut().zip(colors.plane_colors::<4>()) {
      *index = (0..4)
        .find(|&i| cfa.color_at(i / 2, i % 2) == color as usize)
        .ok_or_else(|| input_error!("Superpixel: plane color {:?} doesn't occur in CFA pattern '{}'", color, cfa))?;
    }

    let out = (0..roi.height() / 2)
      .into_par_iter()
      .map(|i| {
        let (r1, r2) = (pixels.row(2 * i), pixels.row(2 * i + 1));
        r1.chunks_exact(2)
          .zip(r2.chunks_exact(2))
          .map(|(a, b)| {
            let superpixel = [a[0], a[1], b[0], b[1]];
            // Map superpixel into correct ordering (CFAPlaneColor)
            [
              superpixel[colormap[0]],
              superpixel[colormap[1]],
              superpixel[colormap[2]],
              superpixel[colormap[3]],
            ]
          })
          .collect::<Vec<_>>()
      })
      .flatten()
      .collect();

    Ok(Color2D::new_with(out, roi.d.w >> 1, roi.d.h >> 1))
  }
}

  #[test]
  fn decodes_a_real_packet() {
    let (header, topology) = nikon();
    let ph = PrecinctHeader::parse(&PACKET0, 0, topology.bands.len()).unwrap();
    let mut precinct = Precinct::empty(&topology, ph.qp, ph.rp);
    let mut r = BitReader::at(&PACKET0, ph.header_len);
    decode_packet(&mut r, &header, &topology, &ph, &mut precinct, &topology.packets[0], None).expect("packet decodes");
    // The packet closes byte-exactly.
    assert_eq!(r.byte_pos(), PACKET0.len());

    assert_eq!(precinct.bands[0].gcli, BAND0_GCLI);
    let coeff: Vec<i16> = precinct.bands[0].coeff.iter().map(|&v| to_signed(v)).collect();
    assert_eq!(coeff, BAND0_COEF);

    assert_eq!(precinct.bands[3].gcli, BAND3_GCLI);
    let coeff: Vec<i16> = precinct.bands[3].coeff.iter().map(|&v| to_signed(v)).collect();
    assert_eq!(coeff, BAND3_COEF);
  }

  /// Cross-check against `precinct0.txt`, the patched SVT-JPEG-XS decoder's
  /// dump of precinct 0 (run it with `NIKON_REF_DUMP` pointing at that file).
  /// See [`super::super::reference`] for how the tests find it.
  #[test]
  fn matches_the_c_reference_dump() {
    let Some(dir) = reference::dir("matches_the_c_reference_dump") else { return };
    let stream = reference::read(&dir, "he_star.jxs");
    let dump = String::from_utf8(reference::read(&dir, "precinct0.txt")).expect("precinct0.txt is UTF-8");
    let header = parse(&stream).unwrap();
    let topology = pi::build(&header).unwrap();
    let (precinct, _) = decode_precinct(&stream, header.first_slice + 6, &header, &topology, None).expect("precinct 0 decodes");

    let mut lines = dump.lines().peekable();
    let mut bands_checked = 0;
    while let Some(line) = lines.next() {
      let Some(rest) = line.strip_prefix("band ") else { continue };
      let fields: Vec<&str> = rest.split_whitespace().collect();
      let comp: usize = fields[0].parse().unwrap();
      let local: usize = fields[1].parse().unwrap();
      let gtli: u8 = fields[5].strip_prefix("gtli=").unwrap().parse().unwrap();
      let id = topology.component_bands[comp].start + local;
      let band = &topology.bands[id];
      let data = &precinct.bands[id];
      assert_eq!(data.gtli, gtli, "gtli of band {} {}", comp, local);
      for row in 0..band.lines_per_precinct {
        let gcli: Vec<u8> = numbers(lines.next().unwrap());
        let coeff: Vec<i16> = numbers(lines.next().unwrap());
        let got_gcli = &data.gcli[row * band.gcli_width..(row + 1) * band.gcli_width];
        let got_coeff: Vec<i16> = data.coeff[row * band.width..(row + 1) * band.width].iter().map(|&v| to_signed(v)).collect();
        assert_eq!(got_gcli, gcli, "GCLIs of band {} {} line {}", comp, local, row);
        assert_eq!(got_coeff, coeff, "coefficients of band {} {} line {}", comp, local, row);
      }
      bands_checked += 1;
    }
    assert_eq!(bands_checked, 25);
  }

  fn numbers<T: std::str::FromStr>(line: &str) -> Vec<T>
  where
    T::Err: std::fmt::Debug,
  {
    let (_, values) = line.split_once(':').expect("a `gcli N:` or `coef N:` line");
    values.split_whitespace().map(|v| v.parse().unwrap()).collect()
  }

  #[test]
  fn decodes_every_precinct_byte_exactly() {
    let Some(dir) = reference::dir("decodes_every_precinct_byte_exactly") else {
      return;
    };
    let stream = reference::read(&dir, "he_star.jxs");
    let header = parse(&stream).unwrap();
    let topology = pi::build(&header).unwrap();
    let mut offset = header.first_slice;
    let mut remaining = header.precinct_count();
    for slice in 0..header.slice_count() {
      assert_eq!(stream[offset..offset + 2], [0xff, 0x20], "SLH of slice {}", slice);
      offset += 6;
      // Vertical prediction chains through the slice and resets at its start.
      let mut top: Option<Precinct> = None;
      for _ in 0..remaining.min(header.slice_height as usize) {
        let (precinct, next) = decode_precinct(&stream, offset, &header, &topology, top.as_ref()).expect("precinct decodes");
        offset = next;
        top = Some(precinct);
        remaining -= 1;
      }
    }
    assert_eq!(remaining, 0);
    assert_eq!(stream[offset..offset + 2], [0xff, 0x11], "EOC after the last precinct");
  }

  #[test]
  fn parses_the_precinct_header() {
    let (_, topology) = nikon();
    let ph = PrecinctHeader::parse(&PACKET0, 0, topology.bands.len()).expect("precinct header parses");
    assert_eq!((ph.payload_len, ph.qp, ph.rp, ph.header_len), (15147, 3, 11, 12));
    assert_eq!(ph.stride(), 15159);
    // Nikon signals significance coding plus vertical prediction everywhere.
    assert!(ph.modes.iter().all(|&m| m == MODE_SIGNIFICANCE | MODE_VERTICAL));
  }


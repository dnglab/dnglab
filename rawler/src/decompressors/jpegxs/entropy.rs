//! Entropy decoding of JPEG XS precincts, as used by Nikon "High Efficiency"
//! NEF. Turns the coded payload of one precinct into per-band GCLI arrays and
//! quantised wavelet coefficients.
//!
//! A precinct is a 12-byte header (for the Nikon layout) followed by eight
//! packets. Each packet covers one line of each band it names and is built
//! from four sub-packets:
//!
//! ```text
//! long header (7 bytes) | significance | GCLI | data | sign
//! ```
//!
//! The header carries only three lengths. The significance sub-packet's size
//! follows from the geometry: one bit per significance group, summed over the
//! packet's bands and rounded up to a byte.
//!
//! Coefficients come out the way the reference decoder stores them, with the
//! magnitude already shifted left by the band's GTLI in the low 15 bits and
//! the sign in bit 15. [`super::dwt`] dequantises them on the way into the
//! transform.

use super::bitreader::BitReader;
use super::header::Header;
use super::pi::Band;
use super::pi::Packet;
use super::pi::Topology;
use crate::RawlerError;
use crate::Result;

/// Largest representable bit-plane count: magnitudes live in 15 bits.
pub const TRUNCATION_MAX: u8 = 15;

pub const SIGN_BIT: u16 = 1 << 15;

/// Per-band 2-bit coding mode, bit 1: the GCLIs are significance-coded.
const MODE_SIGNIFICANCE: u8 = 0b10;
/// Per-band 2-bit coding mode, bit 0: the GCLIs are vertically predicted.
const MODE_VERTICAL: u8 = 0b01;

/// The fixed-size header at the start of every precinct.
#[derive(Debug, Clone)]
pub struct PrecinctHeader {
  /// Payload length in bytes, counted from the end of this header.
  pub payload_len: usize,
  /// Quantisation and refinement for this precinct.
  pub qp: u8,
  pub rp: u8,
  /// 2-bit coding mode per band, indexed by global band id.
  pub modes: Vec<u8>,
  /// Size of this header in bytes: 5 fixed plus the byte-aligned mode bits.
  pub header_len: usize,
}

impl PrecinctHeader {
  pub fn parse(buf: &[u8], offset: usize, band_count: usize) -> Result<Self> {
    let mut r = BitReader::at(buf, offset);
    let fixed = r.bytes(5)?;
    let payload_len = (fixed[0] as usize) << 16 | (fixed[1] as usize) << 8 | fixed[2] as usize;
    let qp = fixed[3];
    let rp = fixed[4];
    let mut modes = Vec::with_capacity(band_count);
    for _ in 0..band_count {
      modes.push(r.bit()? << 1 | r.bit()?);
    }
    r.align();
    Ok(Self {
      payload_len,
      qp,
      rp,
      modes,
      header_len: r.byte_pos() - offset,
    })
  }

  /// Distance from the start of this precinct to the start of the next.
  pub fn stride(&self) -> usize {
    self.header_len + self.payload_len
  }
}

/// Decoded state of one band over one precinct.
#[derive(Debug, Clone)]
pub struct BandData {
  /// Truncation position of this band in this precinct.
  pub gtli: u8,
  /// GCLI per code group, `lines_per_precinct` rows of `gcli_width`.
  pub gcli: Vec<u8>,
  /// Coefficients, `lines_per_precinct` rows of `width`. Magnitude (already
  /// shifted by `gtli`) in the low 15 bits, sign in bit 15.
  pub coeff: Vec<u16>,
}

/// One decoded precinct: every band's GCLIs and coefficients.
#[derive(Debug, Clone)]
pub struct Precinct {
  /// Band data indexed by global band id, as numbered in [`Topology`].
  pub bands: Vec<BandData>,
}

impl Precinct {
  /// Empty band storage, with the truncation positions this precinct's
  /// header calls for.
  fn empty(topology: &Topology, qp: u8, rp: u8) -> Self {
    let bands = topology
      .bands
      .iter()
      .map(|band| BandData {
        gtli: band.gtli(qp, rp, TRUNCATION_MAX),
        gcli: vec![0; band.lines_per_precinct * band.gcli_width],
        coeff: vec![0; band.lines_per_precinct * band.width],
      })
      .collect();
    Self { bands }
  }
}

/// The long-form packet header: a raw-mode flag and the byte lengths of the
/// GCLI, data and sign sub-packets. Nikon streams always use the long form,
/// even though `Lh = 0` and the image is narrow enough that the standard
/// heuristic would select the short one.
#[derive(Debug, Clone, Copy)]
struct PacketHeader {
  raw_mode: bool,
  data_len: usize,
  gcli_len: usize,
  sign_len: usize,
}

impl PacketHeader {
  fn parse(r: &mut BitReader<'_>) -> Result<Self> {
    let m = r.bytes(7)?;
    Ok(Self {
      raw_mode: m[0] >> 7 != 0,
      data_len: ((m[0] as usize & 0x7f) << 13) | (m[1] as usize) << 5 | (m[2] as usize >> 3) & 0x1f,
      gcli_len: ((m[2] as usize & 0x07) << 17) | (m[3] as usize) << 9 | (m[4] as usize) << 1 | m[5] as usize >> 7,
      sign_len: ((m[5] as usize & 0x7f) << 8) | m[6] as usize,
    })
  }
}

/// Decode one precinct starting at `offset`. `top` is the precinct above,
/// which vertical prediction references; pass `None` at the first precinct of
/// a slice. Returns the decoded precinct and the offset of the next one.
pub fn decode_precinct(buf: &[u8], offset: usize, header: &Header, topology: &Topology, top: Option<&Precinct>) -> Result<(Precinct, usize)> {
  if header.group_size != 4 {
    return Err(RawlerError::DecoderFailed(format!(
      "JPEG XS: only Ng = 4 is supported, got {}",
      header.group_size
    )));
  }
  let ph = PrecinctHeader::parse(buf, offset, topology.bands.len())?;
  let end = offset + ph.stride();
  if end > buf.len() {
    return Err(RawlerError::DecoderFailed(format!(
      "JPEG XS: precinct at {} declares {} bytes but only {} remain",
      offset,
      ph.stride(),
      buf.len() - offset
    )));
  }
  let mut precinct = Precinct::empty(topology, ph.qp, ph.rp);
  // Clamp the reader to this precinct so a corrupt packet cannot read into
  // the next one.
  let mut r = BitReader::at(&buf[..end], offset + ph.header_len);
  for packet in &topology.packets {
    decode_packet(&mut r, header, topology, &ph, &mut precinct, packet, top)?;
  }
  Ok((precinct, end))
}

/// The line a band contributes to this packet: a decomposed band's single
/// line, or the precinct line for a suppressed component's band, which spans
/// the full precinct height.
fn band_line(band: &Band, packet: &Packet) -> usize {
  if band.lines_per_precinct > 1 { packet.line } else { 0 }
}

fn decode_packet(
  r: &mut BitReader<'_>,
  header: &Header,
  topology: &Topology,
  ph: &PrecinctHeader,
  precinct: &mut Precinct,
  packet: &Packet,
  top: Option<&Precinct>,
) -> Result<()> {
  let pkt = PacketHeader::parse(r)?;
  let ss = header.sig_group_size as usize;

  if pkt.raw_mode {
    // Raw mode: 4-bit GCLIs, no significance coding.
    let start = r.byte_pos();
    for id in packet.bands.clone() {
      let band = &topology.bands[id];
      let line = band_line(band, packet);
      let out = &mut precinct.bands[id].gcli[line * band.gcli_width..(line + 1) * band.gcli_width];
      for g in out.iter_mut() {
        *g = r.nibble()?;
      }
    }
    r.align();
    finish_subpacket(r, start, pkt.gcli_len, "GCLI")?;
  } else {
    // Significance sub-packet: one bit per significance group, for each band
    // coded that way, in band order and byte-aligned as a whole. A set bit
    // marks the group as insignificant.
    let mut significance: Vec<Option<Vec<u8>>> = Vec::with_capacity(packet.bands.len());
    for id in packet.bands.clone() {
      if ph.modes[id] & MODE_SIGNIFICANCE != 0 {
        let band = &topology.bands[id];
        let bits = (0..band.significance_width).map(|_| r.bit()).collect::<Result<Vec<u8>>>()?;
        significance.push(Some(bits));
      } else {
        significance.push(None);
      }
    }
    r.align();

    // GCLI sub-packet: one continuous VLC bitstream across the packet's
    // bands, byte-aligned only at the end.
    let start = r.byte_pos();
    for (k, id) in packet.bands.clone().enumerate() {
      let band = &topology.bands[id];
      let line = band_line(band, packet);
      let gtli = precinct.bands[id].gtli;
      // Vertical prediction references the previous line of this precinct
      // when line > 0, and the last line of the precinct above when line == 0.
      // At the first precinct of a slice there is no precinct above, and the
      // band falls back to prediction from zero.
      let reference: Option<(Vec<u8>, u8)> = if ph.modes[id] & MODE_VERTICAL == 0 {
        None
      } else if line > 0 {
        let row = &precinct.bands[id].gcli[(line - 1) * band.gcli_width..line * band.gcli_width];
        Some((row.to_vec(), gtli))
      } else if let Some(top) = top {
        let last = band.lines_per_precinct - 1;
        let row = &top.bands[id].gcli[last * band.gcli_width..(last + 1) * band.gcli_width];
        Some((row.to_vec(), top.bands[id].gtli))
      } else {
        None
      };
      let out = &mut precinct.bands[id].gcli[line * band.gcli_width..(line + 1) * band.gcli_width];
      decode_gcli_line(
        r,
        gtli,
        header.rm,
        ss,
        significance[k].as_deref(),
        reference.as_ref().map(|(row, gtli_top)| (row.as_slice(), *gtli_top)),
        out,
      )?;
    }
    r.align();
    finish_subpacket(r, start, pkt.gcli_len, "GCLI")?;
  }

  // Data sub-packet: nibble-interleaved magnitude bit planes.
  let start = r.byte_pos();
  let mut leftover_signs: Vec<u8> = Vec::with_capacity(packet.bands.len());
  for id in packet.bands.clone() {
    let band = &topology.bands[id];
    let line = band_line(band, packet);
    let data = &mut precinct.bands[id];
    let gclis = &data.gcli[line * band.gcli_width..(line + 1) * band.gcli_width];
    let coeff = &mut data.coeff[line * band.width..(line + 1) * band.width];
    leftover_signs.push(decode_data_line(r, gclis, data.gtli, header.fs, coeff)?);
  }
  r.align();
  finish_subpacket(r, start, pkt.data_len, "data")?;

  // Sign sub-packet: one bit per non-zero coefficient, present when Fs = 1.
  if header.fs != 0 {
    let start = r.byte_pos();
    for (k, id) in packet.bands.clone().enumerate() {
      let band = &topology.bands[id];
      let line = band_line(band, packet);
      let coeff = &mut precinct.bands[id].coeff[line * band.width..(line + 1) * band.width];
      for v in coeff.iter_mut() {
        if *v != 0 {
          *v |= (r.bit()? as u16) << 15;
        }
      }
      // The encoder also emitted signs for the non-zero coefficients it
      // decoded past the end of a partial trailing group.
      if !band.width.is_multiple_of(4) {
        r.skip_bits(leftover_signs[k] as usize)?;
      }
    }
    r.align();
    finish_subpacket(r, start, pkt.sign_len, "sign")?;
  }
  Ok(())
}

/// Check a decoded sub-packet against its declared byte length; skip padding
/// when the encoder wrote more than the decode consumed.
fn finish_subpacket(r: &mut BitReader<'_>, start: usize, declared: usize, what: &str) -> Result<()> {
  let used = r.byte_pos() - start;
  if used > declared {
    return Err(RawlerError::DecoderFailed(format!(
      "JPEG XS: {} sub-packet consumed {} bytes but declared {}",
      what, used, declared
    )));
  }
  r.skip_bytes(declared - used)
}

/// The vertical-prediction GCLI update, where `x` is the unary code and
/// `m_top` the clamped reference. There is only so much room to move down
/// before hitting the GTLI, and codes up to twice that room are a zig-zag
/// delta: odd goes down, even goes up. Anything larger keeps going up.
fn vertical_gcli(x: u32, m_top: u8, gtli: u8) -> u8 {
  let x = x as i32;
  let m_top = m_top as i32;
  let threshold = (m_top - gtli as i32).max(0);
  let delta = if x > 2 * threshold {
    x - threshold
  } else if x & 1 == 1 {
    -((x + 1) / 2)
  } else {
    x / 2
  };
  (m_top + delta) as u8
}

/// `significance` holds one flag per group of `ss` GCLIs when the band is
/// significance-coded, and a set flag means the group is skipped.
/// `reference` is the line above and its GTLI when the band is vertically
/// predicted and a reference exists, or `None` to predict from zero.
fn decode_gcli_line(
  r: &mut BitReader<'_>,
  gtli: u8,
  run_mode: u8,
  ss: usize,
  significance: Option<&[u8]>,
  reference: Option<(&[u8], u8)>,
  out: &mut [u8],
) -> Result<()> {
  let significant = |group: usize| significance.is_none_or(|s| s[group] == 0);
  match reference {
    Some((top, gtli_top)) => {
      let t = gtli_top.max(gtli);
      for i in 0..out.len() {
        let m_top = top[i].max(t);
        out[i] = if significant(i / ss) {
          vertical_gcli(r.unary()?, m_top, gtli)
        } else if run_mode != 0 {
          gtli
        } else {
          m_top
        };
      }
    }
    None => {
      for i in 0..out.len() {
        out[i] = if significant(i / ss) { gtli + r.unary()? as u8 } else { gtli };
      }
    }
  }
  Ok(())
}

/// Decode one band line of coefficient magnitudes: per group of 4, `gcli -
/// gtli` bit planes of 4 bits each, MSB plane first, each coefficient's
/// magnitude then shifted left by `gtli`. With `Fs = 0` a nibble of sign bits
/// precedes the planes; with `Fs = 1` signs live in the sign sub-packet.
///
/// Returns how many non-zero coefficients were decoded past the end of a
/// partial trailing group, because the sign sub-packet carries bits for
/// those too.
fn decode_data_line(r: &mut BitReader<'_>, gclis: &[u8], gtli: u8, fs: u8, out: &mut [u16]) -> Result<u8> {
  debug_assert_eq!(gclis.len(), out.len().div_ceil(4));
  let mut leftover_signs = 0u8;
  for (group, &gcli) in gclis.iter().enumerate() {
    let mut vals = [0u16; 4];
    if gcli > gtli {
      let mut signs = [0u16; 4];
      if fs == 0 {
        let s = r.nibble()? as u16;
        for (j, sign) in signs.iter_mut().enumerate() {
          *sign = ((s >> (3 - j)) & 1) << 15;
        }
      }
      // A corrupt stream can carry a GCLI above the largest plane count we
      // can represent, so cap the read the way the reference decoder does.
      let planes = (gcli - gtli).min(TRUNCATION_MAX);
      let mut acc = [0u32; 4];
      for _ in 0..planes {
        let v = r.nibble()? as u32;
        for (j, a) in acc.iter_mut().enumerate() {
          *a = (*a << 1) | ((v >> (3 - j)) & 1);
        }
      }
      for j in 0..4 {
        vals[j] = ((acc[j] << gtli) as u16) | signs[j];
      }
    }
    let start = group * 4;
    let n = (out.len() - start).min(4);
    out[start..start + n].copy_from_slice(&vals[..n]);
    if n < 4 {
      leftover_signs = vals[n..].iter().filter(|&&v| v != 0).count() as u8;
    }
  }
  Ok(leftover_signs)
}

